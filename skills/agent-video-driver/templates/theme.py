# -*- coding: utf-8 -*-
"""
工程唯一配置源: 一支新片要改的一切都收在这个文件里

场景模块 (scene_module.py) 从这里取值, 它自己顶部的同名常量只是没有本文件时的回退,
所以改片只改这一处: 要改的都在下面六段里, 段头写明了改它会连带影响什么.

本文件是纯常量模块, 不 import 任何东西 (不碰 PIL, numpy, canvas),
任何脚本都能安全 import 它而不引入依赖.

输入只有 BPM, DUR, FPS, W, H, FRAME_PREFIX 这几项,
其余的时间派生量 (BEAT, BAR, BARS, NFRAMES) 都跟着它们算, 改了输入不用手改派生值.
"""

# ----------------------------------------------------------------- 身份与署名
# 改这里连带影响: 片尾卡的署名行, 四角 HUD 的作者行, 以及 credits.md 对外声明的作者.
# 是否在片内出现署名由用户决定, 模板默认不画; 要画时从这四个常量取文案, 不要另写一份.
AUTHOR = "JularDepick"
AUTHOR_URL = "https://github.com/JularDepick"
CREDIT_LINE = "JularDepick 出品"
BYLINE = "made by JularDepick"

# ----------------------------------------------------------------- 时间网格
# 改这里连带影响: 画面切点与配乐拍点共用这一条时间轴, 改 BPM 或 DUR 会让拍表, 配乐,
# 排程与全部已渲染帧作废 (连带代价见 SKILL.md 的代价表), 交付前不要动.
# 只有 FPS, BPM, DUR 是输入, 下面四个派生量跟着它们算.
FPS = 30
BPM = 100.0
DUR = 108.0
# 一拍秒数
BEAT = 60.0 / BPM
# 一小节秒数, 4/4 拍; 切点与段落边界一律对齐小节线
BAR = 4.0 * BEAT
# 整小节数, 给 scripts/timing.py 的 --bars 用; 片长不整除小节时它是就近取整
BARS = max(1, int(round(DUR / BAR)))
# 总帧数, 应与 cv.nframes() 一致
NFRAMES = int(round(DUR * FPS))

# ----------------------------------------------------------------- 画幅与排版空间
# 改这里连带影响: 画布尺寸 (configure 会重算数学原点), 四角安全边距, 字幕高度与底部进度线
# 高度都按短边比例重排, 所以换画幅不用改版式代码.
# 16:9 是 1920x1080, 9:16 是 1080x1920, 1:1 是 1080x1080; 自定义宽高必须都是偶数 (编码器要求).
W, H = 1920, 1080
# 帧序列落在 temp/frames_<前缀>/n%05d.png; 换前缀等于换一套帧文件, 合成与验收要跟着换
FRAME_PREFIX = "proj"

# ----------------------------------------------------------------- 色板
# 改这里连带影响: 底板渐变, 数据曲线, 强调元素, 字幕与标注的取色.
# 换风格时底色三色与四个强调色一起换, 风格库见 references/styles.md.
# 色值一律 (R, G, B) 三元组, 每个分量 0 到 255.
# 底色三色: 渐变上端, 渐变下端, 亮场底板
BG_TOP = (9, 17, 35)
BG_BOT = (2, 4, 9)
BG_LIGHT = (8, 19, 38)
# 强调色 1 到 4: 主色, 次色, 正向读数, 警示或反向读数
ACCENT_1 = (56, 225, 255)
ACCENT_2 = (255, 201, 60)
ACCENT_3 = (77, 255, 184)
ACCENT_4 = (255, 77, 157)
# 正文与次级文字
TEXT = (234, 242, 255)
TEXT_DIM = (122, 142, 178)

# ----------------------------------------------------------------- 字体与字号
# 改这里连带影响: 所有上屏文字. 字体键必须存在于 scripts/canvas.py 的 FONT_PATH 表,
# 写了表里没有的键会在渲染前直接抛 KeyError; 缺字形的字会按 canvas 的回退链换字体, 不报错.
# 字号是设计 px 值, 换小画幅时要同步下调; 字距负值收紧, 正值放松.
FONT_TITLE = "cnb"
FONT_TEXT = "cnb"
FONT_MONO = "mono"
FONT_MONO_REGULAR = "monor"
# 副标题
SIZE_SUB = 42
# 幕内大字号
SIZE_EMPHASIS = 64
# 底部字幕
SIZE_CAPTION = 36
# 注释性小字
SIZE_NOTE = 30
TRACK_TITLE = 0.0
TRACK_CAPTION = 0.0

# ----------------------------------------------------------------- 段落与幕表
# 改这里连带影响: 段落数必须与 scene_module.py 的 SCENES 一一对应, 少一段末段会渲不出内容,
# 多一段会多出一个空段; segments 子命令会打印段数与场景函数个数核对.
# SEG 是切点栅格 (秒): 首项 0, 末项等于片尾, 必须严格递增, 相机落位按它走.
# SEG_OF_DEMO 是没有 temp/plan.json 时的段落调度表 (末项等于 DUR), 下面给三幕示例.
# SCREEN_COUNT 是每幕屏数, 要与 script.md 的屏数一致; 有 plan.json 时屏起点读它, 这份只兜底.
SEG = [k * BAR for k in (0, 3, 7, 11, 15, 21, 27, 33, 38, 43, 45)]
SEG_OF_DEMO = [0.0, SEG[1], SEG[2], DUR]
SCREEN_COUNT = [1, 2, 1]
